#pragma once
#include "nas_rules.h"
// These execute in the compiler; they are not hardware/runtime tests.
static_assert(nas::validName("IMG_1234.JPG"), "Camera file name");
static_assert(nas::validName("Mi proyecto-v2.zip"), "Spaces inside name");
static_assert(nas::validName("a"), "Short name");
static_assert(!nas::validName(""), "Empty rejected");
static_assert(!nas::validName(nullptr), "Null rejected");
static_assert(!nas::validName("../secret"), "Traversal rejected");
static_assert(!nas::validName("folder/file"), "Subpath rejected");
static_assert(!nas::validName("folder\\file"), "Backslash rejected");
static_assert(!nas::validName("%2e%2e"), "Encoded path rejected");
static_assert(!nas::validName(".upload.part"), "Internal file rejected");
static_assert(!nas::validName("trailing."), "Trailing dot rejected");
static_assert(!nas::validName(" leading"), "Leading space rejected");
static_assert(!nas::validName("trailing "), "Trailing space rejected");
static_assert(!nas::validName("file\r\nHeader"), "Header injection rejected");
static_assert(!nas::validName("a\"b"), "Quotes rejected");
static_assert(!nas::validName("CON.txt"), "Reserved DOS stem rejected");
static_assert(!nas::validName("LPT9"), "Reserved port rejected");
static_assert(nas::validName("CONcert.txt"), "Reserved prefix alone is okay");
static_assert(!nas::validName("123456789012345678901234567890123456789012345678901234567890123456789012345678901"), "81 chars rejected");
static_assert(nas::validName("12345678901234567890123456789012345678901234567890123456789012345678901234567890"), "80 chars accepted");
static_assert(nas::canStart(0, nas::RESERVE), "Empty file supported");
static_assert(!nas::canStart(0, nas::RESERVE - 1), "Reserve protected");
static_assert(nas::canStart(nas::MAX_FILE, nas::MAX_FILE + nas::RESERVE), "Max size accepted");
static_assert(!nas::canStart(nas::MAX_FILE + 1, UINT64_MAX), "Max size enforced");
static_assert(!nas::canStart(2, nas::RESERVE + 1), "Full storage rejected");
static_assert(nas::canAppend(4, 6, 10), "Last chunk accepted");
static_assert(!nas::canAppend(4, 7, 10), "Oversized chunk rejected");
static_assert(!nas::canAppend(UINT64_MAX, 1, 10), "Counter overflow rejected");
static_assert(!nas::canAppend(4, UINT64_MAX, 10), "Chunk overflow rejected");
static_assert(nas::complete(0, 0) && nas::complete(10, 10), "Exact completion");
static_assert(!nas::complete(9, 10) && !nas::complete(11, 10), "Partial/excess rejected");
static_assert(nas::recoverCalibration(false,true,false,false), "Uncalibrated touch can recover");
static_assert(!nas::recoverCalibration(false,true,true,false), "Held touch does not loop calibration");
static_assert(!nas::recoverCalibration(false,true,false,true), "Transfer is not interrupted by calibration");
static_assert(!nas::recoverCalibration(true,true,false,false), "Calibrated input stays in normal controls");
static_assert(nas::pairUsable(true,100,200), "Live pair token");
static_assert(!nas::pairUsable(false,100,200), "Consumed token rejected");
static_assert(!nas::pairUsable(true,200,200), "Expiry instant rejected");
static_assert(!nas::pairUsable(true,201,200), "Expired token rejected");
static_assert(nas::pairUsable(true,UINT32_MAX-10,15), "Millis wrap accepted");
static_assert(!nas::pairUsable(true,16,15), "Wrapped deadline expired");
static_assert([](){bool a=true;return nas::acceptPair(a,100,200,true)&&!a&&!nas::acceptPair(a,101,200,true);}(),"Pair token cannot replay");
static_assert([](){bool a=true;return !nas::acceptPair(a,100,200,false)&&a;}(),"Bad token does not consume valid token");
static_assert([](){bool a=true;return !nas::acceptPair(a,200,200,true);}(),"Expired token cannot pair");
static_assert([](){nas::TouchGate g;g.update(true,10);return !g.sample(29)&&g.sample(30)&&g.sample(31);}(),"A failed first sample remains retryable");
static_assert([](){nas::TouchGate g;g.update(true,10);g.consume();return !g.sample(40);}(),"Held touch cannot repeat action");
static_assert([](){nas::TouchGate g;g.update(true,10);g.consume();g.update(false,20);g.update(true,30);return g.sample(50);}(),"Release permits next press");
